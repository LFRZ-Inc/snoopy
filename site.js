function applyLang(lang) {
  const dict = copy[lang] || copy.en;
  document.documentElement.lang = lang === "es" ? "es" : "en";
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const value = dict[el.dataset.i18n];
    if (value) el.textContent = value;
  });
  const toggle = document.querySelector("[data-lang-toggle]");
  if (toggle) toggle.textContent = lang === "es" ? "EN" : "ES";
  try { localStorage.setItem("snoopy-lang", lang); } catch { /* preview only */ }
}

document.querySelector("[data-lang-toggle]")?.addEventListener("click", () => {
  const next = document.documentElement.lang === "es" ? "en" : "es";
  applyLang(next);
});

document.querySelector("[data-menu]")?.addEventListener("click", () => {
  document.querySelector(".nav")?.classList.toggle("open");
});

document.querySelector("[data-preview-form]")?.addEventListener("submit", (event) => {
  event.preventDefault();
  event.currentTarget.classList.add("hidden");
  document.querySelector("[data-thanks]")?.classList.add("show");
});

const saved = (() => {
  try { return localStorage.getItem("snoopy-lang"); } catch { return null; }
})();
if (saved === "es") applyLang("es");
